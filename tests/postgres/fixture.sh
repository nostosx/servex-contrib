#!/usr/bin/env bash
# Explicit fixture ownership; only labeled containers/networks created here are removed.
set -Eeuo pipefail
root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd -P)"
fixture_tmp=''
action="${1:?usage: fixture.sh up profile env-file | down env-file}"
validate_name() { [[ "$name" =~ ^servex-[a-zA-Z0-9_-]+$ ]]; }
cleanup() {
  validate_name || return 1
  local resource label
  for resource in "$name" "$name-peer" "$name-worker"; do
    label="$(docker inspect -f '{{index .Config.Labels "servex.postgres.fixture"}}' "$resource" 2>/dev/null || true)"
    if [ "$label" = "$name" ]; then docker rm -f -v "$resource"; fi
  done
  label="$(docker network inspect -f '{{index .Labels "servex.postgres.fixture"}}' "$name-net" 2>/dev/null || true)"
  if [ "$label" = "$name" ]; then docker network rm "$name-net"; fi
  if [ -n "$fixture_tmp" ]; then rm -rf -- "$fixture_tmp"; fi
}
if [ "$action" = down ]; then
  env_file="${2:?env-file required}"
  # This file is generated by up and must be kept private to the calling job.
  # shellcheck disable=SC1090
  source "$env_file"
  name="$SERVEX_FIXTURE_NAME"
  cleanup
  exit 0
fi
[ "$action" = up ] || { echo 'Unknown action' >&2; exit 1; }
profile="${2:?profile required}"
case "$profile" in base|general|timescale|citus|duckdb) ;; *) echo 'Unknown profile' >&2; exit 1 ;; esac
env_file="${3:?env-file required}"
name="${SERVEX_FIXTURE_NAME:-servex-pg-$profile-$$-$RANDOM}"
validate_name || { echo 'Invalid fixture name' >&2; exit 1; }
# Refuse to overwrite ownership metadata or reuse a preexisting resource.
[ ! -e "$env_file" ] || { echo 'env-file already exists' >&2; exit 1; }
if docker container inspect "$name" >/dev/null 2>&1 || docker network inspect "$name-net" >/dev/null 2>&1; then
  echo 'Fixture name already exists' >&2; exit 1
fi
umask 077
printf 'SERVEX_FIXTURE_NAME=%q\n' "$name" > "$env_file"
trap 'trap - ERR; cleanup' ERR
fixture_tmp="$(mktemp -d)"
# Bootstrap container TLS from a checksum-pinned Debian CA package, fetched by
# the host's already configured HTTPS client. APT still verifies signed indexes.
curl --retry 3 -fsSL https://deb.debian.org/debian-security/pool/updates/main/c/ca-certificates/ca-certificates_20250419+deb13u1_all.deb -o "$fixture_tmp/ca.deb"
image="${SERVEX_POSTGRES_IMAGE:-postgres:17}"
docker network create --label "servex.postgres.fixture=$name" "$name-net"
start() {
  local container="$1"
  docker run -d --name "$container" --label "servex.postgres.fixture=$name" \
    --network "$name-net" -p 127.0.0.1::5432 \
    -e POSTGRES_USER=servex -e POSTGRES_PASSWORD=servex -e POSTGRES_DB=servex_it \
    -e POSTGRES_HOST_AUTH_METHOD=trust "$image"
}
ready() {
  local container="$1" attempt
  for ((attempt=0;attempt<90;attempt++)); do
    if docker exec "$container" psql -h 127.0.0.1 -U servex -d servex_it -Atc 'SELECT 1' >/dev/null 2>&1; then return; fi
    sleep 1
  done
  docker logs "$container"; return 1
}
sql() { docker exec "$1" psql -U servex -d servex_it -v ON_ERROR_STOP=1 -c "$2"; }
install() {
  docker cp "$root/tests/postgres/install.sh" "$1:/tmp/servex-install.sh"
  docker cp "$fixture_tmp/ca.deb" "$1:/tmp/servex-ca.deb"
  docker exec "$1" bash /tmp/servex-install.sh "$2"
}
port() { docker port "$1" 5432/tcp | awk -F: '{print $NF}'; }
put() { printf '%s=%q\n' "$1" "$2" >> "$env_file"; }
for optional in SERVEX_IT_POSTGRES_CAPABILITIES SERVEX_IT_VECTOR_INDEX_KINDS SERVEX_IT_SEARCH_ENGINES SERVEX_IT_POSTGRES_PEER_DSN SERVEX_IT_POSTGRES_PEER_HOST SERVEX_IT_CITUS_WORKER_DSN SERVEX_IT_POSTGRES_HTTP_URL; do
  put "$optional" ''
done
start "$name"
ready "$name"
install "$name" "$profile"
case "$profile" in
  base) preload='pg_cron,pg_search,pg_stat_statements,pgaudit'; extensions='vector pgmq pg_cron pg_search pgroonga pg_trgm postgis pg_stat_statements pgaudit hypopg postgres_fdw pg_partman' ;;
  general) preload='vchord,pg_net,pg_ivm,pgaudit,pg_stat_statements'; extensions='vector vectorscale vchord pg_jsonschema age pg_ivm pg_net pg_repack pg_partman pgaudit hypopg pg_stat_statements postgres_fdw postgis' ;;
  timescale) preload=timescaledb; extensions=timescaledb ;;
  citus) preload=citus; extensions=citus ;;
  duckdb) preload=pg_duckdb; extensions=pg_duckdb ;;
esac
preload_sql="$(printf '%s' "$preload" | sed "s/,/','/g")"
sql "$name" "ALTER SYSTEM SET shared_preload_libraries='$preload_sql'"
sql "$name" 'ALTER SYSTEM SET max_worker_processes=16'
if [ "$profile" = base ]; then
  sql "$name" "ALTER SYSTEM SET cron.database_name='servex_it'"
  sql "$name" 'ALTER SYSTEM SET cron.use_background_workers=on'
elif [ "$profile" = general ]; then
  sql "$name" "ALTER SYSTEM SET pg_net.database_name='servex_it'"
fi
docker restart "$name"
ready "$name"
for extension in $extensions; do
  if [ "$extension" = pg_partman ]; then
    sql "$name" 'CREATE SCHEMA partman; CREATE EXTENSION pg_partman WITH SCHEMA partman'
  else
    sql "$name" "CREATE EXTENSION $extension CASCADE"
  fi
done
put SERVEX_IT_POSTGRES_DSN "postgres://servex:servex@127.0.0.1:$(port "$name")/servex_it?sslmode=disable"
put SERVEX_IT_POSTGRES_EXTENSIONS "$extensions"
put SERVEX_IT_POSTGRES_CONTAINER "$name"
case "$profile" in
  base) put SERVEX_IT_SEARCH_ENGINES 'native pg_search pgroonga pg_trgm' ;;
  general)
    start "$name-peer"; ready "$name-peer"
    put SERVEX_IT_POSTGRES_PEER_DSN "postgres://servex:servex@127.0.0.1:$(port "$name-peer")/servex_it?sslmode=disable"
    put SERVEX_IT_POSTGRES_PEER_HOST "$name-peer"
    put SERVEX_IT_POSTGRES_CAPABILITIES 'jsonschema ivm age partman spatial hypopg statistics audit repack net fdw'
    put SERVEX_IT_VECTOR_INDEX_KINDS 'diskann vchordrq'
    temporary="$(mktemp -d)"
    arch="$(docker exec "$name" dpkg --print-architecture)"
    CGO_ENABLED=0 GOOS=linux GOARCH="$arch" "${GO:-go}" build -o "$temporary/http-target" "$root/.github/scripts/postgreshttp/main.go"
    docker cp "$temporary/http-target" "$name:/tmp/servex-http-target"
    rm -rf -- "$temporary"
    docker exec -d "$name" /tmp/servex-http-target
    docker exec "$name" curl --retry 10 --retry-connrefused --retry-delay 1 -fsS http://127.0.0.1:8089/health
    put SERVEX_IT_POSTGRES_HTTP_URL http://127.0.0.1:8089
    ;;
  timescale|duckdb) put SERVEX_IT_POSTGRES_CAPABILITIES "$profile" ;;
  citus)
    start "$name-worker"; ready "$name-worker"; install "$name-worker" citus
    sql "$name-worker" "ALTER SYSTEM SET shared_preload_libraries='citus'"
    docker restart "$name-worker"; ready "$name-worker"
    sql "$name-worker" 'CREATE EXTENSION citus'
    sql "$name" 'ALTER SYSTEM SET citus.shard_count=4'
    sql "$name" "SELECT citus_set_coordinator_host('$name',5432); SELECT citus_add_node('$name-worker',5432); SELECT pg_reload_conf()"
    put SERVEX_IT_CITUS_WORKER_DSN "postgres://servex:servex@127.0.0.1:$(port "$name-worker")/servex_it?sslmode=disable"
    put SERVEX_IT_POSTGRES_CAPABILITIES citus
    ;;
esac
rm -rf -- "$fixture_tmp"
fixture_tmp=''
trap - ERR
printf 'Fixture ready. Load its environment with: set -a; source %q; set +a\n' "$env_file"
